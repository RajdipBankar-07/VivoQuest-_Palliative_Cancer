import mongoose, { Schema, Document, Model } from 'mongoose';

export type SyncOperationType =
  | 'status_update'
  | 'clinical_documentation'
  | 'installation_verification'
  | 'visit_exception';

export type SyncOperationStatus = 'applied' | 'conflict' | 'failed';

export interface ISyncOperation extends Document {
  clientOperationId: string; // Unique idempotency key generated by client
  providerId: mongoose.Types.ObjectId;
  providerName: string;
  providerPhone?: string;
  visitId: mongoose.Types.ObjectId;
  visitNumber: string;
  operationType: SyncOperationType;
  clientTimestamp: Date;
  syncedAt: Date;
  status: SyncOperationStatus;
  payload: any;
  result?: any;
  conflictDetails?: {
    serverStatus?: string;
    expectedStatus?: string;
    reason?: string;
  };
  errorReason?: string;
  retryCount: number;
  createdAt: Date;
  updatedAt: Date;
}

const SyncOperationSchema = new Schema<ISyncOperation>(
  {
    clientOperationId: {
      type: String,
      required: true,
      unique: true,
      index: true,
      trim: true,
    },
    providerId: {
      type: Schema.Types.ObjectId,
      ref: 'User',
      required: true,
      index: true,
    },
    providerName: {
      type: String,
      required: true,
      trim: true,
    },
    providerPhone: {
      type: String,
      trim: true,
    },
    visitId: {
      type: Schema.Types.ObjectId,
      ref: 'FieldVisit',
      required: true,
      index: true,
    },
    visitNumber: {
      type: String,
      required: true,
      index: true,
    },
    operationType: {
      type: String,
      enum: ['status_update', 'clinical_documentation', 'installation_verification', 'visit_exception'],
      required: true,
    },
    clientTimestamp: {
      type: Date,
      required: true,
    },
    syncedAt: {
      type: Date,
      default: Date.now,
      index: true,
    },
    status: {
      type: String,
      enum: ['applied', 'conflict', 'failed'],
      required: true,
      index: true,
    },
    payload: {
      type: Schema.Types.Mixed,
      required: true,
    },
    result: {
      type: Schema.Types.Mixed,
    },
    conflictDetails: {
      serverStatus: String,
      expectedStatus: String,
      reason: String,
    },
    errorReason: {
      type: String,
    },
    retryCount: {
      type: Number,
      default: 0,
    },
  },
  {
    timestamps: true,
  }
);

// Compound indexes for administrative querying and reconciliation
SyncOperationSchema.index({ providerId: 1, syncedAt: -1 });
SyncOperationSchema.index({ visitId: 1, clientOperationId: 1 });
SyncOperationSchema.index({ status: 1, createdAt: -1 });

export const SyncOperation: Model<ISyncOperation> =
  mongoose.models.SyncOperation || mongoose.model<ISyncOperation>('SyncOperation', SyncOperationSchema);
